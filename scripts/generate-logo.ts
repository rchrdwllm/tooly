// Pre-renders assets/logo.png into a pixel grid (src/generated/logo.ts) used by
// the half-block fallback in src/components/Logo.tsx.
// We downscale with a smooth filter, then snap every pixel to a clean palette
// (white / yellow / transparent) so no grey anti-aliasing fringe is left.
// Requires ImageMagick. Run: npm run generate:logo
import {execFileSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';

const WIDTH = 80; // terminal columns
const HEIGHT = 18; // pixel rows (2 per terminal row, must be even); a half-row is ~1.35x taller than a column is wide
const THRESHOLD = 120; // brightness needed to count as a drawn pixel
const WHITE = 'ffffff';
const YELLOW = 'fee786';

const out = execFileSync(
  'magick',
  ['assets/logo.png', '-background', 'black', '-alpha', 'remove', '-filter', 'lanczos', '-resize', `${WIDTH}x${HEIGHT}!`, '-depth', '8', 'txt:-'],
  {encoding: 'utf8', maxBuffer: 1 << 26},
);

const rows: string[][] = Array.from({length: HEIGHT}, () => Array(WIDTH).fill(''));
for (const line of out.split('\n')) {
  const m = line.match(/^(\d+),(\d+):.*?#([0-9A-Fa-f]{6})/);
  if (!m) continue;
  const [r, g, b] = [0, 2, 4].map(i => parseInt(m[3]!.slice(i, i + 2), 16)) as [number, number, number];
  const max = Math.max(r, g, b);
  if (max >= THRESHOLD) rows[Number(m[2])]![Number(m[1])] = (max - Math.min(r, g, b)) / max > 0.25 ? YELLOW : WHITE;
}

writeFileSync(
  'src/generated/logo.ts',
  `// AUTO-GENERATED by scripts/generate-logo.ts — do not edit.\n` +
    `// Each cell is a hex colour, or '' for transparent.\n` +
    `export const LOGO_PIXELS: string[][] = ${JSON.stringify(rows)};\n`,
);
console.log(`logo: ${WIDTH}x${HEIGHT} px -> ${WIDTH}x${HEIGHT / 2} cells`);
